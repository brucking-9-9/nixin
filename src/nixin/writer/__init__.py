def _package_hints(ctx: Ctx, key: str) -> list[str]:
    ws, sc = ctx.ws, ctx.scope
    hints = []
    leaf = parse_attrpath(key)[-1]
    exact, _, _ = ws.option_decls(sc.mods, ("programs", leaf, "enable"))
    for f in exact:
        flag = " --home " + sc.name if sc.kind == "home" else ""
        hints.append(
            f"programs.{leaf}.enable is set at {f.where}: "
            f"`nixin unset programs.{leaf}.enable{flag}` or set it to false"
        )
    other_scopes: list[Scope] = []
    try:
        if sc.kind == "nixos":
            nixos = ws.closure(_roots_of(ws, sc.host))
            for user in ws.hm_users(nixos):
                other_scopes.append(_scope(ws, sc.host, user, use_eval=False))
        else:
            other_scopes.append(_scope(ws, sc.host, None, use_eval=False))
    except NixinError:
        pass
    for o in other_scopes:
        for f in ws.package_decls(o.mods, o.list_option):
            if _matches_pkg(f, key):
                flag = f"--home {o.name}" if o.kind == "home" else "without --home"
                hints.append(f"declared in {'.'.join(o.list_option)} at {f.where} (use {flag})")
    files = {m.file for m in sc.mods}
    cited = {h.split(" at ", 1)[1].split(":", 1)[0] for h in hints if " at " in h}
    for m in scan.grep_package(ws.root, leaf, limit=200):
        if m.file in files and m.file not in cited and m.score >= 2 and len(hints) < 6:
            hints.append(f"mentioned at {m.file}:{m.line}: {m.text.strip()[:80]}")
    return hints


def _roots_of(ws: Workspace, host: str) -> list[ModRef]:
    return ws.flake_hosts().get(host) or []


def _not_found(what: str, scope: Scope, hints: list[str]) -> WriterError:
    msg = f"{what} is not declared in any module of {scope.label} nixin can edit"
    if hints:
        msg += "; " + "; ".join(hints)
    return WriterError("not-found", msg, hints=hints)


