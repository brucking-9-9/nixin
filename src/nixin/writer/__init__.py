"""writer — change the config: `add`, `rm`, `set`, `unset` on a user-owned workspace clone.

New things go to tool-owned generated modules rendered from installer/state.json
(`installer/<host>.nix` for NixOS, `installer/<user>-home.nix` for Home Manager), imported
once from the host's (or the HM user's) entry module. Removing or changing something a
hand-written module declares edits that module in place, on token offsets found by the
writer's own scanner (nixtext.py). Everything is computed in memory first: an error
writes nothing, `--dry-run` prints the diff and writes nothing.

`register(subparsers)` is the only thing cli.py calls (same pattern as truth).
"""

