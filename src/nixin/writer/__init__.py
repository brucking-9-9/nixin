from .workspace import HEADER, Found, ModRef, Workspace, WriterError

VERBS = ("add", "rm", "set", "unset")
IMPORT_COMMENT = "# generated by nixin (installer/state.json)"
EVAL_TIMEOUT = 900.0
TOOLS: Tools = Tools()  # tests swap these two for fakes
NIX: NixRunner = run_nix


def register(sub: argparse._SubParsersAction) -> None:
    handlers = {"add": add, "rm": rm, "set": set_, "unset": unset}
    for verb, handler in handlers.items():
        p = sub.choices.get(verb)
        if p is None:
            p = sub.add_parser(verb)
            p.add_argument("args", nargs="*")
        p.add_argument("--config", help="workspace clone (default: $NIXIN_CONFIG)")
        p.add_argument("--home", metavar="USER", help="the Home Manager user instead of NixOS")
        p.add_argument("--dry-run", action="store_true", help="print the diff, write nothing")
        p.add_argument(
            "--no-eval", action="store_true", help="skip the nix eval checks (text + parse only)"
        )
        if verb != "add":
            p.add_argument(
                "--where",
                action="append",
                metavar="FILE:LINE",
                help="pick one of several declarations (repeatable)",
            )
        p.set_defaults(run=handler)


# --- shared machinery -------------------------------------------------------------------


@dataclass
class Scope:
    kind: str  # "nixos" | "home"
    name: str  # host or HM user
    host: str
    mods: list[ModRef]
    site: ModRef | None  # where the generated module gets imported

    @property
    def gen(self) -> str:
        return generated_file(self.kind, self.name)

    @property
    def list_option(self) -> tuple[str, ...]:
        return tuple(LIST_OPTION[self.kind].split("."))

    @property
    def label(self) -> str:
        return self.host if self.kind == "nixos" else f"{self.name}@{self.host} (Home Manager)"


@dataclass
class Txn:
    """Pending edits per file; nothing touches the disk until write()."""

    ws: Workspace
    orig: dict[str, str | None] = field(default_factory=dict)
    edits: dict[str, list[Edit]] = field(default_factory=dict)
    replaced: dict[str, str | None] = field(default_factory=dict)

    def original(self, rel: str) -> str | None:
        if rel not in self.orig:
            self.orig[rel] = self.ws.text(rel) if self.ws.exists(rel) else None
        return self.orig[rel]

    def edit(self, rel: str, e: Edit) -> None:
        self.original(rel)
        self.edits.setdefault(rel, []).append(e)

    def put(self, rel: str, text: str | None) -> None:
        self.original(rel)
        self.replaced[rel] = text

    def final(self, rel: str) -> str | None:
        if rel in self.replaced:
            return self.replaced[rel]
        text = self.original(rel)
        if text is None or rel not in self.edits:
            return text
        return edits.apply(text, self.edits[rel])

    def changed(self) -> list[str]:
        files = set(self.edits) | set(self.replaced)
        return sorted(f for f in files if self.final(f) != self.original(f))


@dataclass
class Ctx:
    ns: argparse.Namespace
    ws: Workspace
    scope: Scope
    state: State
    old_state: State
    txn: Txn
    warnings: list[str] = field(default_factory=list)
    actions: list[dict[str, Any]] = field(default_factory=list)
    imports_added: list[dict[str, Any]] = field(default_factory=list)
    imports_removed: list[dict[str, Any]] = field(default_factory=list)

    @property
    def use_eval(self) -> bool:
        return not self.ns.no_eval


def _run(ns: argparse.Namespace, fn) -> dict[str, Any]:
    try:
        Workspace.open(ns.config, nix=NIX)  # config errors first, like truth's verbs
        return fn(ns)
    except NixinError as e:
        return e.doc()


def _context(ns: argparse.Namespace) -> Ctx:
    ws = Workspace.open(ns.config, nix=NIX)
    scope = _scope(ws, ns.host, ns.home, use_eval=not ns.no_eval)
    state = State.load(ws)
    return Ctx(ns, ws, scope, state, State.load(ws), Txn(ws))


def _scope(ws: Workspace, host: str, user: str | None, *, use_eval: bool) -> Scope:
    try:
        hosts = ws.flake_hosts()
    except NixSyntaxError as e:
        raise NixinError("invalid-nix", f"flake.nix: {e}") from e
    roots = hosts.get(host)
    if host not in hosts:
        known = sorted(hosts)
        if use_eval and not known:
            known = ws.repo.hosts()  # flake.nix built in a way the scanner cannot read
        if host not in known:
            raise NixinError(
                "unknown-host", f"{host!r} is not in nixosConfigurations ({', '.join(known)})"
            )
    if roots is None:  # helper function, flake-parts, …: fall back to the usual layout
        roots = [
            ModRef(f)
            for f in (f"hosts/{host}/default.nix", f"hosts/{host}/configuration.nix")
            if ws.exists(f)
        ][:1]
        ws.warnings.append(
            f"could not read the modules of {host} from flake.nix; using "
            + (roots[0].file if roots else "no entry module")
        )
    mods = ws.closure(roots)
    files = [m for m in roots if not m.inline]
    if user is None:
        return Scope("nixos", host, host, mods, files[0] if files else None)
    users = ws.hm_users(mods)
    if user not in users:
        others = [
            h for h, r in hosts.items() if h != host and r and user in ws.hm_users(ws.closure(r))
        ]
        hint = f"; it is one on {', '.join(others)} (use --host)" if others else ""
        raise NixinError(
            "unknown-user",
            f"{user!r} is not a Home Manager user of {host} "
            f"(users: {', '.join(sorted(users)) or 'none'}){hint}",
        )
    hm_roots = users[user]
    hm_files = [m for m in hm_roots if not m.inline]
    site = hm_files[0] if hm_files else hm_roots[0]
    return Scope("home", user, host, ws.closure(hm_roots), site)


def _parse_where(ns: argparse.Namespace) -> list[tuple[str, int]]:
    out = []
    for w in getattr(ns, "where", None) or []:
        file, _, line = w.rpartition(":")
        if not file or not line.isdigit():
            raise NixinError("usage", f"--where takes FILE:LINE, got {w!r}")
        out.append((os.path.normpath(file).replace(os.sep, "/"), int(line)))
    return out


def _pick(found: list[Found], where: list[tuple[str, int]], what: str) -> list[Found]:
    """The declarations to act on; several without --where is `ambiguous`."""
    if where:
        picked = [f for f in found if (f.file, f.line) in where]
        if not picked and found:
            raise WriterError(
                "not-found",
                f"{what}: no declaration at {', '.join(f'{f}:{n}' for f, n in where)}; "
                f"it is declared at {', '.join(f.where for f in found)}",
                candidates=[f.doc() for f in found],
            )
        return picked
    if len(found) > 1:
        raise WriterError(
            "ambiguous",
            f"{what} is declared in {len(found)} places: "
            + ", ".join(f"{f.where} ({f.text})" for f in found)
            + "; pick one with --where FILE:LINE",
            candidates=[f.doc() for f in found],
        )
    return found


def _pkg_key(name: str) -> str:
    try:
        parts = parse_attrpath(name)
    except ValueError as e:
        raise NixinError("invalid-nix", f"package {name!r}: {e}") from e
    if parts[0] == "pkgs" and len(parts) > 1:
        parts = parts[1:]
    return attr_key(parts)


def _option_parts(name: str) -> list[str]:
    try:
        return parse_attrpath(name)
    except ValueError as e:
        raise NixinError("invalid-nix", f"option {name!r}: {e}") from e


def _matches_pkg(f: Found, key: str) -> bool:
    return f.text in (key, f"pkgs.{key}")


def _same_expr(a: str, b: str) -> bool:
    try:
        x, y = NixFile(a), NixFile(b)
    except NixSyntaxError:
        return a.strip() == b.strip()
    return x.compact(0, len(x.toks)) == y.compact(0, len(y.toks))


def _rel_import(site: ModRef, gen: str) -> str:
    rel = os.path.relpath(gen, os.path.dirname(site.file) or ".").replace(os.sep, "/")
    return rel if rel.startswith("../") else f"./{rel}"


def _import_refs(ctx: Ctx, gen: str) -> list[tuple[ModRef, NixFile, Any, int]]:
    """(module, file, list shape, element index) of every `imports` entry naming gen,
    whether or not gen exists yet."""
    out = []
    for m in ctx.scope.mods:
        if m.file == gen:
            continue
        try:
            nf = ctx.ws.parsed(m.file)
            _, special = nf.module_defs(m.lo, m.hi)
        except (OSError, NixSyntaxError):
            continue
        for d in special:
            if d.path != ("imports",):
                continue
            for sh in nf.shapes(d.binding.val_lo, d.binding.val_hi):
                if sh.kind != "list":
                    continue
                for i, e in enumerate(nf.list_elements(sh.lo + 1, sh.hi - 1)):
                    p = nf.elem_path(e)
                    if p is None:
                        continue
                    target = os.path.normpath(os.path.join(os.path.dirname(m.file), p))
                    if target.replace(os.sep, "/") == gen:
                        out.append((m, nf, sh, i))
    return out


def _sync_generated(ctx: Ctx) -> None:
    """Re-render the scope's generated module from state; wire or unwire its import."""
    sc, txn, state = ctx.scope, ctx.txn, ctx.state
    gen = sc.gen
    entry = state.peek(sc.kind, sc.name)
    old = txn.original(gen)
    if old is not None and not old.startswith(HEADER):
        raise NixinError(
            "file-conflict", f"{gen} exists and was not generated by nixin; move it away first"
        )
    refs = _import_refs(ctx, gen)
    if not entry["packages"] and not entry["options"]:
        if old is not None:
            txn.put(gen, None)
        for m, nf, sh, i in refs:
            original = state.imports.pop(m.file, None)
            e, restored = edits.remove_from_list(nf, sh, i, original)
            txn.edit(m.file, e)
            ctx.imports_removed.append(
                {"file": m.file, "line": nf.line_of(nf.toks[sh.lo].start), "restored": restored}
            )
        return
    text, why = TOOLS.fmt(render(sc.kind, entry))
    if why:
        ctx.warnings.append(why)
    if old is not None and old != text:
        before = ctx.old_state.peek(sc.kind, sc.name)
        if old != TOOLS.fmt(render(sc.kind, before))[0]:
            ctx.warnings.append(f"{gen} had been edited by hand; re-rendered from {STATE_FILE}")
    txn.put(gen, text)
    if len(refs) > 1:
        ctx.warnings.append(f"{gen} is imported {len(refs)} times")
    if refs:
        return
    site = sc.site
    if site is None:
        raise WriterError(
            "import-site-missing",
            f"no entry module found for {sc.label}; import {gen} from it yourself",
            line=f"imports = [ ./{gen} ];",
        )
    rel = _rel_import(site, gen)
    nf = ctx.ws.parsed(site.file)
    _, special = nf.module_defs(site.lo, site.hi)
    lists = [
        sh
        for d in special
        if d.path == ("imports",)
        for sh in nf.shapes(d.binding.val_lo, d.binding.val_hi)
        if sh.kind == "list"
    ]
    if not lists:
        line = f"imports = [ {rel} ];"
        raise WriterError(
            "import-site-missing",
            f"{site.file} has no `imports = [ … ];` list; add this line to its attribute set: "
            f"{line}",
            file=site.file,
            line=line,
        )
    e, original = edits.insert_into_list(nf, lists[0], f"{rel} {IMPORT_COMMENT}")
    txn.edit(site.file, e)
    if original is not None:
        state.imports[site.file] = original
    ctx.imports_added.append({"file": site.file, "import": rel})


def _validate_value(expr: str) -> None:
    """Syntax only. A value lands inside a module, so it may name the module's arguments
    (`pkgs`, `lib`, `config`, specialArgs such as `inputs`); a bare `nix-instantiate
    --parse` resolves names while parsing and rejects those as undefined variables. Under
    `with { };` every free name is a dynamic lookup and the grammar is unchanged, so this
    accepts exactly the well-formed expressions. Names are checked where the value lands
    (the edited file is parsed before anything is written), types and semantics by the
    eval after the write (checks.eval)."""
    err = TOOLS.parse(f"with {{ }};\n{expr}")
    if err is None:
        return
    err = TOOLS.parse(expr) or err  # the same syntax error, positions in the user's own text
    raise NixinError(
        "invalid-nix",
        f"not a Nix expression: {err}\n(only the syntax is checked here; whether the value "
        "suits the option is shown by the eval after the write: checks.eval, warnings)",
    )


def _finish(ctx: Ctx, fields: dict[str, Any], summary: str, check=None) -> dict[str, Any]:
    """Validate, diff, write (unless --dry-run), prove it still parses/evaluates."""
    ws, txn, state = ctx.ws, ctx.txn, ctx.state
    state.prune()
    new_state = None if state.is_empty() else state.text()
    if new_state != txn.original(STATE_FILE):
        txn.put(STATE_FILE, new_state)
    changed = txn.changed()
    for rel in changed:
        if not ws.inside(rel):
            raise NixinError("not-a-workspace", f"{rel} resolves outside {ws.root}")
        p = ws.abspath(rel)
        target = p if p.exists() else next(d for d in p.parents if d.exists())
        if not os.access(target, os.W_OK):
            raise NixinError("not-a-workspace", f"{rel} is not writable by you")
        text = txn.final(rel)
        if rel.endswith(".nix") and text is not None:
            err = TOOLS.parse(text)
            if err is not None:
                raise WriterError(
                    "invalid-nix", f"{rel} would not parse after the edit: {err}", file=rel
                )
    changes = []
    for rel in changed:
        old, new = txn.original(rel), txn.final(rel)
        kind = "created" if old is None else "deleted" if new is None else "modified"
        changes.append({"file": rel, "kind": kind, "diff": edits.unified(rel, old, new)})
    dry = ctx.ns.dry_run
    checks: dict[str, Any] = {"parse": [], "eval": None}
    if not dry and changes:
        for rel in changed:
            _write(ws, rel, txn.final(rel))
        _git_track(
            ws,
            [c["file"] for c in changes if c["kind"] == "created"],
            [c["file"] for c in changes if c["kind"] == "deleted"],
            ctx.warnings,
        )
        for c in changes:
            if c["file"].endswith(".nix") and c["kind"] != "deleted":
                err = TOOLS.parse(ws.text(c["file"]))
                checks["parse"].append({"file": c["file"], "ok": err is None, "error": err})
        if ctx.use_eval and check is not None:
            checks["eval"] = check()
            if not checks["eval"].get("ok"):
                ctx.warnings.append(
                    f"{checks['eval'].get('code', 'eval-failed')}: "
                    f"{checks['eval'].get('message', '')}".strip()
                )
    warnings = fields.setdefault("warnings", [])
    for w in [*ws.warnings, *ctx.warnings]:
        if w not in warnings:
            warnings.append(w)
    doc = {
        "ok": True,
        "config": str(ws.root),
        "scope": ctx.scope.kind,
        "user": ctx.scope.name if ctx.scope.kind == "home" else None,
        "dry_run": dry,
        **fields,
        "actions": ctx.actions,
        "changes": changes,
        "imports_added": ctx.imports_added,
        "imports_removed": ctx.imports_removed,
        "checks": checks,
    }
    if not ctx.ns.json:
        doc["message"] = _render(doc, summary)
    return doc


def _render(doc: dict[str, Any], summary: str) -> str:
    out = [c["diff"].rstrip("\n") for c in doc["changes"]]
    ev = doc["checks"].get("eval")
    tail = ""
    if ev:
        tail = f"; eval {'ok' if ev.get('ok') else 'FAILED'}"
        if ev.get("note"):
            tail += f": {ev['note']}"
    files = ", ".join(f"{c['file']} ({c['kind']})" for c in doc["changes"]) or "no files changed"
    prefix = "dry run, nothing written: " if doc["dry_run"] else ""
    out += [f"warning: {w}" for w in doc.get("warnings", [])]
    out.append(f"{prefix}{summary} — {files}{tail}")
    return "\n".join(out)


def _write(ws: Workspace, rel: str, text: str | None) -> None:
    p = ws.abspath(rel)
    if text is None:
        p.unlink(missing_ok=True)
        if p.parent != ws.root and p.parent.is_dir() and not any(p.parent.iterdir()):
            p.parent.rmdir()
        return
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(f".{p.name}.nixin-tmp")
    tmp.write_bytes(text.encode())
    if p.exists():
        shutil.copymode(p, tmp)
    os.replace(tmp, p)


def _git_track(ws: Workspace, created: list[str], deleted: list[str], warnings: list[str]):
    """Flakes only see files git knows: intent-to-add what nixin created, and forget again
    what it deletes if it was never committed."""
    if not (ws.root / ".git").exists() or shutil.which("git") is None:
        return
    git = ["git", "-c", "safe.directory=*", "-C", str(ws.root)]
    if created:
        proc = subprocess.run(
            [*git, "add", "--intent-to-add", "--", *created],
            check=False,
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            warnings.append(f"git add -N failed: {proc.stderr.strip()}")
    for rel in deleted:
        in_head = subprocess.run(
            [*git, "cat-file", "-e", f"HEAD:{rel}"], check=False, capture_output=True, text=True
        )
        if in_head.returncode != 0:
            subprocess.run(
                [*git, "rm", "--cached", "--quiet", "--ignore-unmatch", "--", rel],
                check=False,
                capture_output=True,
                text=True,
            )


# --- eval checks ------------------------------------------------------------------------


def _list_expr(sc: Scope) -> str:
    if sc.kind == "nixos":
        return "c.config.environment.systemPackages"
    return f"c.config.home-manager.users.{nix_attr(sc.name)}.home.packages"


def _attr_lists(keys: list[str]) -> str:
    return nix_value([parse_attrpath(k) for k in keys])


def _eval_or_error(ctx: Ctx, apply: str) -> tuple[Any, dict[str, Any] | None]:
    repo = ctx.ws.repo
    try:
        return repo.eval_json(
            repo.host_attr(ctx.scope.host), apply=apply, timeout=EVAL_TIMEOUT
        ), None
    except NixinError as e:
        return None, {"ok": False, "code": e.code, "message": e.message}


def _missing_packages(ctx: Ctx, keys: list[str]) -> list[str]:
    """Attribute paths that do not exist in the host's pkgs (one small eval)."""
    apply = f"c: map (a: c.pkgs.lib.hasAttrByPath a c.pkgs) {_attr_lists(keys)}"
    got, err = _eval_or_error(ctx, apply)
    if err is not None:
        ctx.warnings.append(f"could not check the package names: {err['message']}")
        return []
    return [k for k, ok in zip(keys, got, strict=True) if not ok]


def _check_packages(ctx: Ctx, added: list[str], removed: list[str]):
    sc = ctx.scope
    keys = added + removed

    def check() -> dict[str, Any]:
        apply = (
            "c: let lib = c.pkgs.lib; in { "
            f'installed = map (p: p.name or "?") {_list_expr(sc)}; '
            "wanted = map (a: let r = builtins.tryEval (lib.attrByPath a null c.pkgs); in "
            "if r.success && r.value != null then (r.value.name or null) else null) "
            f"{_attr_lists(keys)}; }}"
        )
        got, err = _eval_or_error(ctx, apply)
        attr = f"{ctx.ws.repo.host_attr(sc.host)}.{_list_expr(sc).removeprefix('c.')}"
        cmd = f"nix eval --json {ctx.ws.root}#{attr} --apply 'map (p: p.name)'"
        if err is not None:
            return {**err, "attr": attr, "command": cmd}
        installed = set(got["installed"])
        names = dict(zip(keys, got["wanted"], strict=True))
        present = {k: names[k] for k in added if names[k] in installed}
        still = {k: names[k] for k in removed if names[k] in installed}
        doc: dict[str, Any] = {
            "ok": len(present) == len(added) and not still,
            "attr": attr,
            "command": cmd,
            "packages": len(installed),
            "present": present,
            "absent": [k for k in removed if k not in still],
        }
        opt = ".".join(sc.list_option)
        notes = [f"{n} in {opt}" for n in present.values()]
        notes += [f"{k} no longer in {opt}" for k in doc["absent"]]
        if still:
            doc["still_installed"] = still
            notes += [
                f"{n} STILL installed (another definition provides it)" for n in still.values()
            ]
        if len(present) != len(added):
            doc["missing"] = [k for k in added if k not in present]
        doc["note"] = ", ".join(notes)
        return doc

    return check


def _check_option(ctx: Ctx, parts: list[str]):
    sc = ctx.scope
    base = "c.config" if sc.kind == "nixos" else f"c.config.home-manager.users.{nix_attr(sc.name)}"

    def check() -> dict[str, Any]:
        apply = (
            "c: let lib = c.pkgs.lib; "
            f"r = builtins.tryEval (lib.attrByPath {nix_value(parts)} {{ __nixinUnset = true; }} {base}); "
            "v = r.value; in "
            "if !r.success then { __nixinError = true; } "
            'else if builtins.isFunction v then "<function>" '
            'else if lib.isDerivation v then "<derivation ${v.name}>" else v'
        )
        got, err = _eval_or_error(ctx, apply)
        attr = f"{ctx.ws.repo.host_attr(sc.host)}.{base.removeprefix('c.')}.{attr_key(parts)}"
        if err is not None:
            return {**err, "attr": attr}
        if isinstance(got, dict) and got.get("__nixinError"):
            return {
                "ok": False,
                "code": "eval-failed",
                "attr": attr,
                "message": f"{attr_key(parts)} does not evaluate",
            }
        if isinstance(got, dict) and got.get("__nixinUnset"):
            return {
                "ok": True,
                "attr": attr,
                "defined": False,
                "note": f"{attr_key(parts)} has no value",
            }
        shown = json.dumps(got) if not isinstance(got, (dict, list)) else "{…}"
        return {"ok": True, "attr": attr, "value": got, "note": f"{attr_key(parts)} = {shown}"}

    return check


