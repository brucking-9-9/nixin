def add(ns: argparse.Namespace) -> dict[str, Any]:
    return _run(ns, _add)


def _add(ns: argparse.Namespace) -> dict[str, Any]:
    if not ns.args:
        raise NixinError("usage", "add PKG... [--home USER]")
    keys = list(dict.fromkeys(_pkg_key(a) for a in ns.args))
    ctx = _context(ns)
    sc, ws = ctx.scope, ctx.ws
    declared = ws.package_decls(sc.mods, sc.list_option)
    entry = ctx.state.entry(sc.kind, sc.name)
    new: list[str] = []
    for key in keys:
        hits = [f for f in declared if _matches_pkg(f, key)]
        if key in entry["packages"]:
            ctx.actions.append({"name": key, "action": "already-added", "file": sc.gen})
        elif hits:
            ctx.actions.append(
                {
                    "name": key,
                    "action": "already-declared",
                    "file": hits[0].file,
                    "line": hits[0].line,
                }
            )
        else:
            new.append(key)
    if new and ctx.use_eval:
        missing = _missing_packages(ctx, new)
        if missing:
            raise NixinError(
                "unknown-package",
                f"not in the pkgs of {sc.host}: {', '.join(missing)} (try `nixin search`)",
            )
    for key in new:
        entry["packages"].append(key)
        ctx.actions.append({"name": key, "action": "added", "file": sc.gen})
    if new:
        _sync_generated(ctx)
    summary = f"added {', '.join(new)} to {sc.label}" if new else f"nothing to add to {sc.label}"
    skipped = [a for a in ctx.actions if a["action"] != "added"]
    if skipped:
        summary += (
            " (already there: "
            + ", ".join(
                f"{a['name']} {a['file']}" + (f":{a['line']}" if a.get("line") else "")
                for a in skipped
            )
            + ")"
        )
    check = _check_packages(ctx, new, []) if new else None
    return _finish(ctx, {"packages": keys}, summary, check)


def rm(ns: argparse.Namespace) -> dict[str, Any]:
    return _run(ns, _rm)


def _rm(ns: argparse.Namespace) -> dict[str, Any]:
    if not ns.args:
        raise NixinError("usage", "rm PKG... [--home USER] [--where FILE:LINE]")
    keys = list(dict.fromkeys(_pkg_key(a) for a in ns.args))
    ctx = _context(ns)
    sc, ws, state = ctx.scope, ctx.ws, ctx.state
    where = _parse_where(ns)
    declared = ws.package_decls(sc.mods, sc.list_option)
    entry = state.entry(sc.kind, sc.name)
    removed: list[str] = []
    in_state = False
    unused = set(where)
    for key in keys:
        hits = [f for f in declared if _matches_pkg(f, key)]
        # --where applies to the packages it names a declaration of
        mine = [w for w in where if any((h.file, h.line) == w for h in hits)]
        unused.difference_update(mine)
        picked = _pick(hits, mine, key)
        if not picked and key not in entry["packages"]:
            raise _not_found(key, sc, _package_hints(ctx, key))
        for f in picked:
            ctx.txn.edit(f.file, edits.removal(ctx.txn.original(f.file), f.start, f.end))
            ctx.actions.append({"name": key, "action": "removed", "file": f.file, "line": f.line})
            if f.conditional:
                ctx.warnings.append(
                    f"{key} at {f.where} was in a conditional list (mkIf/optionals)"
                )
        if key in entry["packages"]:
            entry["packages"].remove(key)
            in_state = True
            ctx.actions.append({"name": key, "action": "removed", "file": sc.gen})
        removed.append(key)
    if unused:
        raise WriterError(
            "not-found",
            "--where names no declaration of "
            + ", ".join(keys)
            + ": "
            + ", ".join(f"{f}:{n}" for f, n in sorted(unused)),
        )
    if in_state:
        _sync_generated(ctx)
    places = sorted({a["file"] for a in ctx.actions})
    summary = f"removed {', '.join(removed)} from {sc.label} ({', '.join(places)})"
    return _finish(ctx, {"packages": keys}, summary, _check_packages(ctx, [], removed))


def set_(ns: argparse.Namespace) -> dict[str, Any]:
    return _run(ns, _set)


def _set(ns: argparse.Namespace) -> dict[str, Any]:
    if len(ns.args) < 2:
        raise NixinError("usage", "set OPTION NIX-EXPR [--home USER]")
    parts = _option_parts(ns.args[0])
    key = attr_key(parts)
    value = " ".join(ns.args[1:]).strip()
    _validate_value(value)
    ctx = _context(ns)
    sc, ws, state = ctx.scope, ctx.ws, ctx.state
    exact, covering, _below = ws.option_decls(sc.mods, tuple(parts))
    picked = _pick(exact, _parse_where(ns), key)
    entry = state.entry(sc.kind, sc.name)
    for f in covering:
        ctx.warnings.append(
            f"{f.option} is also defined at {f.where} as an expression nixin cannot look into"
        )
    if picked:
        f = picked[0]
        s, e = f.value_span
        old = ctx.txn.original(f.file)[s:e]
        if _same_expr(old, value):
            ctx.actions.append({"name": key, "action": "unchanged", "file": f.file, "line": f.line})
        else:
            ctx.txn.edit(f.file, Edit(s, e, value))
            ctx.actions.append(
                {
                    "name": key,
                    "action": "set",
                    "file": f.file,
                    "line": f.line,
                    "old": old,
                    "in_place": True,
                }
            )
        if f.wrappers:
            ctx.warnings.append(f"{key} at {f.where} keeps its {', '.join(f.wrappers)} wrapper")
        if f.conditional:
            ctx.warnings.append(f"{key} at {f.where} is conditional (mkIf); still conditional")
        if key in entry["options"]:
            del entry["options"][key]
            ctx.warnings.append(f"{key} was also in {STATE_FILE}; removed there")
            _sync_generated(ctx)
        summary = f"set {key} = {value} in {f.where} (edited in place)"
    else:
        old = entry["options"].get(key)
        if old is not None and old == value:
            ctx.actions.append({"name": key, "action": "unchanged", "file": sc.gen})
        else:
            entry["options"][key] = value
            ctx.actions.append({"name": key, "action": "set", "file": sc.gen, "old": old})
        _sync_generated(ctx)
        summary = f"set {key} = {value} for {sc.label} in {sc.gen}"
    return _finish(ctx, {"option": key, "value": value}, summary, _check_option(ctx, parts))


def unset(ns: argparse.Namespace) -> dict[str, Any]:
    return _run(ns, _unset)


def _unset(ns: argparse.Namespace) -> dict[str, Any]:
    if len(ns.args) != 1:
        raise NixinError("usage", "unset OPTION [--home USER] [--where FILE:LINE]")
    parts = _option_parts(ns.args[0])
    key = attr_key(parts)
    ctx = _context(ns)
    sc, ws, state = ctx.scope, ctx.ws, ctx.state
    exact, covering, below = ws.option_decls(sc.mods, tuple(parts))
    entry = state.entry(sc.kind, sc.name)
    picked = _pick(exact, _parse_where(ns), key)
    if not picked and key not in entry["options"]:
        hints = [f"{f.option} is set at {f.where}" for f in below[:6]]
        hints += [
            f"{f.option} at {f.where} is an expression nixin cannot look into" for f in covering
        ]
        raise _not_found(key, sc, hints)
    for f in picked:
        ctx.txn.edit(f.file, edits.removal(ctx.txn.original(f.file), f.start, f.end))
        ctx.actions.append({"name": key, "action": "unset", "file": f.file, "line": f.line})
    if key in entry["options"]:
        del entry["options"][key]
        ctx.actions.append({"name": key, "action": "unset", "file": sc.gen})
        _sync_generated(ctx)
    places = sorted({a["file"] for a in ctx.actions})
    summary = f"unset {key} for {sc.label} ({', '.join(places)})"
    return _finish(ctx, {"option": key}, summary, _check_option(ctx, parts))
