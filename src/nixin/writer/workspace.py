"""The user-owned workspace clone: which modules make up a host or a Home Manager user,
and where in them a package or an option is declared.

Everything here is text: flake.nix gives the hosts and their `modules = [ … ]`, the
`imports` lists give the closure, `home-manager.users.<name>` bindings give the HM users.
No eval, so it works for a host that does not evaluate and costs milliseconds. What it
cannot see (modules imported through an expression, not a path literal) is reported as a
warning, never guessed at.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..configrepo import DEFAULT_CONFIG, ENV_CONFIG, ConfigRepo, NixinError, NixRunner, run_nix
from .nixtext import Def, NixFile, NixSyntaxError, Shape

GENERATED_DIR = "installer"
HEADER = "# generated by nixin — edit state.json or use the CLI"


class WriterError(NixinError):
    """A NixinError that carries extra fields in its error object (e.g. candidates)."""

    def __init__(self, code: str, message: str, **extra: Any) -> None:
        super().__init__(code, message)
        self.extra = extra

    def doc(self) -> dict[str, Any]:
        d = super().doc()
        d["error"].update(self.extra)
        return d


@dataclass(frozen=True)
class ModRef:
    """A module: a whole file, or an inline module expression (token range) inside one."""

    file: str  # repo-relative, posix
    lo: int = 0
    hi: int | None = None

    @property
    def inline(self) -> bool:
        return self.hi is not None


@dataclass
class Found:
    """One declaration in a hand-written module: a list element or a binding."""

    kind: str  # "element" | "binding"
    file: str
    line: int
    start: int  # character span in the file
    end: int
    text: str
    option: str  # the option it belongs to (environment.systemPackages, services.x.enable)
    conditional: bool = False
    value_span: tuple[int, int] | None = None  # bindings: the value (inside priority wrappers)
    wrappers: tuple[str, ...] = ()

    @property
    def where(self) -> str:
        return f"{self.file}:{self.line}"

    def doc(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "file": self.file,
            "line": self.line,
            "text": self.text,
            "option": self.option,
        }
        if self.conditional:
            d["conditional"] = True
        if self.wrappers:
            d["wrappers"] = list(self.wrappers)
        return d


def _first_line(s: str) -> str:
    line = s.strip().splitlines()[0] if s.strip() else ""
    return line if len(line) <= 120 else line[:119] + "…"


@dataclass
class Workspace:
    root: Path
    repo: ConfigRepo
    warnings: list[str] = field(default_factory=list)
    _parsed: dict[str, NixFile] = field(default_factory=dict, repr=False)

    @classmethod
    def open(cls, explicit: str | None, nix: NixRunner = run_nix) -> Workspace:
        raw = explicit or os.environ.get(ENV_CONFIG) or DEFAULT_CONFIG
        given = Path(os.path.abspath(Path(raw).expanduser()))
        etc = Path(DEFAULT_CONFIG)
        if given == etc or (etc.exists() and given.resolve() == etc.resolve()):
            raise NixinError(
                "not-a-workspace",
                f"{given} is the authoritative config; nixin edits a user-owned clone "
                f"(git clone {etc} ~/nixos, then --config ~/nixos or {ENV_CONFIG})",
            )
        repo = ConfigRepo.locate(str(given), nix=nix)
        if not os.access(repo.path, os.W_OK):
            raise NixinError(
                "not-a-workspace", f"{repo.path} is not writable by you; use a clone you own"
            )
        return cls(repo.path, repo)

    # --- files ------------------------------------------------------------------------

    def abspath(self, rel: str) -> Path:
        return self.root / rel

    def inside(self, rel: str) -> bool:
        """True if rel (following symlinks) stays inside the workspace."""
        p = os.path.realpath(self.root / rel)
        return p == str(self.root) or p.startswith(str(self.root) + os.sep)

    def exists(self, rel: str) -> bool:
        return (self.root / rel).is_file()

    def text(self, rel: str) -> str:
        return (self.root / rel).read_bytes().decode()

    def parsed(self, rel: str) -> NixFile:
        if rel not in self._parsed:
            self._parsed[rel] = NixFile(self.text(rel))
        return self._parsed[rel]

    def is_generated(self, rel: str) -> bool:
        if not rel.startswith(GENERATED_DIR + "/") or not self.exists(rel):
            return False
        return self.text(rel).startswith(HEADER)

    def resolve(self, from_rel: str, path_text: str) -> str | None:
        """Repo-relative file a path literal in from_rel names (a dir means default.nix)."""
        if not path_text.startswith(("./", "../")) and path_text not in (".", ".."):
            return None
        base = os.path.dirname(from_rel)
        rel = os.path.normpath(os.path.join(base, path_text))
        if rel.startswith(".."):
            return None
        if (self.root / rel).is_dir():
            rel = os.path.join(rel, "default.nix")
        rel = rel.replace(os.sep, "/")
        return rel if self.exists(rel) else None

    # --- modules ----------------------------------------------------------------------

    def module_defs(self, m: ModRef) -> tuple[list[Def], list[Def]]:
        return self.parsed(m.file).module_defs(m.lo, m.hi)

    def flake_hosts(self) -> dict[str, list[ModRef] | None]:
        """nixosConfigurations.<host> -> its `modules` (None: built some way nixin cannot read)."""
        nf = self.parsed("flake.nix")
        hosts: dict[str, list[ModRef] | None] = {}
        for d in nf.walk(nf.module_shapes()):
            if d.path != ("outputs",):
                continue
            out = nf.module_shapes(d.binding.val_lo, d.binding.val_hi)
            for od in nf.walk(out):
                if len(od.path) == 2 and od.path[0] == "nixosConfigurations" and od.path[1]:
                    hosts[od.path[1]] = self._system_modules(nf, od)
        return hosts

    def _system_modules(self, nf: NixFile, d: Def) -> list[ModRef] | None:
        b = d.binding
        for i in range(b.val_lo, b.val_hi):
            t = nf.toks[i]
            if t.kind == "id" and t.text == "nixosSystem" and nf.kind(i + 1) == "{":
                attrs = Shape("attrs", i + 1, nf.match[i + 1] + 1)
                for md in nf.walk([attrs]):
                    if md.path == ("modules",):
                        return self._module_list(nf, "flake.nix", md)
                return []
        return None

    def _module_list(self, nf: NixFile, file: str, d: Def) -> list[ModRef]:
        """The modules an `imports`/`modules` list names: files, and inline modules."""
        out: list[ModRef] = []
        for _sh, e in nf.list_items(d):
            p = nf.elem_path(e)
            if p is not None:
                target = self.resolve(file, p)
                if target is None:
                    if p.startswith(("./", "../")):
                        self.warnings.append(f"{file}: import {p} not found in the workspace")
                    continue
                out.append(ModRef(target))
            elif nf.kind(e.lo) == "{":
                out.append(ModRef(file, e.lo, e.hi))
            elif nf.kind(e.lo) == "(" and nf.match[e.lo] == e.hi - 1:
                inner = nf.module_shapes(e.lo + 1, e.hi - 1)
                if any(s.kind == "attrs" for s in inner):
                    out.append(ModRef(file, e.lo + 1, e.hi - 1))
        return out

    def closure(self, roots: list[ModRef]) -> list[ModRef]:
        """Every module reachable through `imports` path literals, roots first."""
        seen: set[ModRef] = set()
        out: list[ModRef] = []
        queue = list(roots)
        while queue:
            m = queue.pop(0)
            if m in seen:
                continue
            seen.add(m)
            out.append(m)
            try:
                nf = self.parsed(m.file)
                _defs, special = self.module_defs(m)
            except (OSError, NixSyntaxError) as e:
                self.warnings.append(f"could not scan {m.file}: {e}")
                continue
            for d in special:
                if d.path == ("imports",):
                    queue.extend(self._module_list(nf, m.file, d))
        return out

    def hm_users(self, nixos_mods: list[ModRef]) -> dict[str, list[ModRef]]:
        """home-manager.users.<name> = import ./x.nix | ./x.nix | { … } in the host's modules."""
        users: dict[str, list[ModRef]] = {}
        for m in nixos_mods:
            if self.is_generated(m.file):
                continue
            try:
                defs, _ = self.module_defs(m)
            except (OSError, NixSyntaxError):
                continue
            nf = self.parsed(m.file)
            for d in defs:
                if len(d.path) != 3 or d.path[:2] != ("home-manager", "users") or not d.path[2]:
                    continue
                b = d.binding
                lo, hi = b.val_lo, b.val_hi
                if nf.kind(lo) == "id" and nf.toks[lo].text == "import" and hi - lo == 2:
                    lo += 1
                ref: ModRef | None = None
                if hi - lo == 1 and nf.kind(lo) == "path":
                    target = self.resolve(m.file, nf.toks[lo].text)
                    ref = ModRef(target) if target else None
                elif any(s.kind == "attrs" for s in nf.module_shapes(lo, hi)):
                    ref = ModRef(m.file, lo, hi)
                if ref is not None:
                    users.setdefault(d.path[2], []).append(ref)
        return users

    # --- finding declarations ---------------------------------------------------------

    def hand_written(self, mods: list[ModRef]) -> list[ModRef]:
        return [m for m in mods if not self.is_generated(m.file)]

    def package_decls(self, mods: list[ModRef], option: tuple[str, ...]) -> list[Found]:
        """Every element of every list literal assigned to `option` in the modules."""
        out: list[Found] = []
        for m in self.hand_written(mods):
            try:
                defs, _ = self.module_defs(m)
            except (OSError, NixSyntaxError):
                continue
            nf = self.parsed(m.file)
            for d in defs:
                if d.path != option:
                    continue
                for sh, e in nf.list_items(d):
                    s, end = nf.span(e.lo, e.hi)
                    out.append(
                        Found(
                            "element",
                            m.file,
                            nf.line_of(s),
                            s,
                            end,
                            nf.compact(e.lo, e.hi),
                            ".".join(option),
                            conditional=d.conditional or sh.conditional,
                        )
                    )
        return out

    def option_decls(
        self, mods: list[ModRef], path: tuple[str, ...]
    ) -> tuple[list[Found], list[Found], list[Found]]:
        """(exact definitions, opaque ancestors, descendants) of an option path."""
        exact: list[Found] = []
        covering: list[Found] = []
        below: list[Found] = []
        n = len(path)
        for m in self.hand_written(mods):
            try:
                defs, _ = self.module_defs(m)
            except (OSError, NixSyntaxError):
                continue
            nf = self.parsed(m.file)
            for d in defs:
                if None in d.path:
                    continue
                b = d.binding
                s, end = nf.toks[b.start].start, nf.toks[b.val_hi].end
                f = Found(
                    "binding",
                    m.file,
                    nf.line_of(s),
                    s,
                    end,
                    _first_line(nf.text[s:end]),
                    ".".join(d.path),
                    conditional=d.conditional,
                )
                if d.path == path:
                    shapes = nf.shapes(b.val_lo, b.val_hi)
                    lo, hi = b.val_lo, b.val_hi
                    if len(shapes) == 1 and (shapes[0].wrappers or shapes[0].conditional):
                        # keep `lib.mkForce`/`lib.mkIf c` & co, replace what they wrap
                        f.wrappers = shapes[0].wrappers
                        f.conditional = f.conditional or shapes[0].conditional
                        lo, hi = shapes[0].lo, shapes[0].hi
                    f.value_span = (nf.toks[lo].start, nf.toks[hi - 1].end)
                    exact.append(f)
                elif len(d.path) < n and path[: len(d.path)] == d.path:
                    if not any(s.kind == "attrs" for s in nf.shapes(b.val_lo, b.val_hi)):
                        covering.append(f)
                elif len(d.path) > n and d.path[:n] == path:
                    below.append(f)
        return exact, covering, below
